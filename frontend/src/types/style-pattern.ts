/**
 * Представляет собой один стилистический или нарративный паттерн,
 * извлеченный из текста с помощью LLM.
 */
export interface StylePattern {
  id: string;
  /**
   * Назначение, функция этого куска текста.
   * Например: "Экспозиция персонажа", "Описание локации через детали", "Создание саспенса".
   */
  function: string;
  /**
   * Сам текстовый фрагмент.
   */
  text: string;
}
